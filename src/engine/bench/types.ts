export interface BenchAttachment {
  id: string;
  name: string;
  text: string;
}

export interface BenchStep {
  text: string;
  attachments?: BenchAttachment[];
  expect: 'block' | 'allow';
}

export interface BenchSample {
  id: string;
  dataset: DatasetId;
  title?: string;
  text: string;
  attachments?: BenchAttachment[];
  expect: 'block' | 'allow';
  /** Expected categories for a block (empty for allow). */
  categories: CategoryId[];
  /** Generated by Aionix (not from the source corpus); reported separately and combined. */
  augmented?: boolean;
  /** Source label whose value fails its checksum — counted as allow, reported in its own bucket. */
  checksumInvalid?: boolean;
  /** Multi-step scenario (e.g. chip added, then removed). Each step must match. */
  steps?: BenchStep[];
  note?: string;
}

export interface Adjudication {
  expect: 'block' | 'allow';
  categories: CategoryId[];
  reason: string;
}
